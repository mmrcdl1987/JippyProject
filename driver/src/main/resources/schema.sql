CREATE TABLE IF NOT EXISTS jippy_driver.driver(
    driver_id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    first_name character varying(50) NOT NULL,
    last_name character varying(50) NOT NULL,
    phone_number character varying(15) NOT NULL,
    email character varying(100),
    nominee_name character varying(50),
    nominee_phone_number character varying(15),
    is_nominee_verified BOOLEAN DEFAULT FALSE,
    family_member_name character varying(50),
    family_member_phone_number character varying(15),
    is_family_member_verified BOOLEAN DEFAULT FALSE,
    created_at timestamp without time zone,
    created_by integer,
    updated_at timestamp without time zone,
    updated_by integer,
    CONSTRAINT driver_pkey PRIMARY KEY (driver_id)

);

