        ON UPDATE NO ACTION ON DELETE NO ACTION
);

-- 11. Driver Current Location
CREATE TABLE IF NOT EXISTS jippy_driver.driver_current_location(
    driver_location_id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
