CREATE TABLE jippy_driver.zones (
    zone_id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    zone_name character varying(100) NOT NULL,
    boundary GEOGRAPHY(POLYGON, 4326) NOT NULL,
    zone_type character varying(30) NOT NULL, --DRIVER-ZONE,COMMUNITY
	created_at timestamp without time zone,
    created_by integer,
    updated_at timestamp without time zone,
    updated_by integer,
    CONSTRAINT zones_pkey PRIMARY KEY (zone_id)
);
CREATE INDEX boundary_idx ON jippy_driver.zones USING GIST (boundary);

